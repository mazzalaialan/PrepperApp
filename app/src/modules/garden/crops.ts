export function cropName(c: Crop, lang: string): string {
  return lang.startsWith('en') ? c.name.en : c.name.es;
}

export function text(x: Text, lang: string): string {
  return lang.startsWith('en') ? x.en : x.es;
}

/** Tamaño de un cuadro de la grilla de canteros, cm. */
export const CELL_CM = 30;

/**
 * Cuánto ocupa una planta en la grilla: cuántas entran en un cuadro, o
 * cuántos cuadros por lado necesita una sola (huerta intensiva, distancia
 * pareja en todas las direcciones).
 */
export function gridFootprint(c: Crop): { perCell: number; side: number } {
  if (c.spacingCm <= CELL_CM) return { perCell: Math.max(1, Math.floor(CELL_CM / c.spacingCm) ** 2), side: 1 };
  return { perCell: 1, side: Math.max(1, Math.round(c.spacingCm / CELL_CM)) };
}
