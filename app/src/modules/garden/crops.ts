export type Family =
  | 'amaranth' // Quenopodiáceas (acelga, espinaca, remolacha)
  | 'allium' // Liliáceas / aliáceas
  | 'mint' // Labiadas
  | 'carrot' // Apiáceas / umbelíferas
  | 'legume' // Fabáceas
  | 'bindweed' // Convolvuláceas (batata)
  | 'nightshade' // Solanáceas
  | 'cabbage' // Brasicáceas / crucíferas
  | 'grass' // Gramíneas (maíz)
  | 'daisy' // Asteráceas / compuestas
  | 'rose' // Rosáceas (frutilla)
  | 'gourd' // Cucurbitáceas
  | 'asparagus'; // Asparagáceas

/** Grupo para la rotación clásica de la huerta: hojas, raíces, bulbos, frutos, legumbres. */
export type CropGroup = 'leaf' | 'root' | 'bulb' | 'fruit' | 'legume';

/** Ante la helada: resiste, resiste las suaves, o se quema. */
export type FrostTolerance = 'hardy' | 'half' | 'tender';

export type RootDepth = 'shallow' | 'medium' | 'deep';

export interface Text {
  es: string;
  en: string;
}

export interface Crop {
  id: string;
  name: Text;
  family: Family;
  group: CropGroup;
  frost: FrostTolerance;
  /** Aguanta media sombra (menos de 6 h de sol directo). */
  shade: boolean;
  /** Se puede hacer en maceta o recipiente. */
  container: boolean;
  /** Siembra directa, almácigo y trasplante, o las dos. */
  sowing: 'direct' | 'transplant' | 'both';
  /** Distancia entre plantas en la huerta intensiva (cantero), cm. */
  spacingCm: number;
  /** Distancia entre líneas a campo, cm (referencia). */
  rowCm: number;
  /** Días desde la siembra directa (o desde el trasplante) hasta empezar a cosechar. */
  daysToHarvest: [number, number];
  /** Días en el almácigo hasta trasplantar. */
  nurseryDays?: [number, number];
  /** Cuántos meses se sigue cosechando una vez que empieza. */
  harvestMonths: number;
  /** Perenne: se planta una vez y produce varios años. */
  perennial?: boolean;
  /** Se cosecha recién a partir del año N (espárrago). */
  firstHarvestYear?: number;
  rootDepth: RootDepth;
  /** Coeficiente de cultivo FAO-56: al inicio, en pleno desarrollo y al final. */
  kc: [number, number, number];
  /** Se lleva bien con (ids de cultivos). */
  companions: string[];
  /** Aromáticas y flores que ayudan (no son cultivos de la lista). */
  companionHerbs?: Text;
  /** Se perjudican mutuamente. */
  avoid: string[];
  /** Conviene sembrarlo después de estos grupos. */
  rotateAfter: CropGroup[];
  /** Cuándo le hace más falta el agua. */
  waterCritical: Text;
  /** Rendimiento orientativo. */
  yield: Text;
  /** Cómo y cuándo se cosecha. */
  harvest: Text;
  /** Unidad sugerida para registrar la cosecha. */
  harvestUnit: 'kg' | 'u' | 'atados';
}

