/** Usos donde hay que practicar con un instructor. */
export const RISKY_USES: ReadonlySet<KnotUse> = new Set(['rappel', 'rescue']);

export interface KnotStep {
  text: L;
  /** Imagen de este paso (public/knots/). */
  img?: string;
}

