export function creditFor(file: string): ImageCredit | undefined {
  // El más específico primero (ej.: "as-de-guia-doble" antes que "as-de-guia").
  return [...IMAGE_CREDITS].sort((a, b) => b.match.length - a.match.length).find((c) => file.startsWith(c.match));
}

/** Todas las imágenes de un nudo: las de cada paso y las de la secuencia. */
export function knotImages(k: Knot): string[] {
  return [...new Set([...k.images, ...k.steps.map((s) => s.img).filter((x): x is string => !!x)])];
}
